#!/usr/bin/env python3
"""Render the site's numbers from the claims register.

Every count on bawbel.io comes from one place: the `expect` values in
claims/register.yaml in bawbel/.github. That repository's verifier checks each value
against the code. This script writes them into the stat block of index.html, between
the stat:start and stat:end markers, and a count typed anywhere else fails --check.

    python scripts/sync_site_numbers.py           # rewrite the stat block
    python scripts/sync_site_numbers.py --check   # exit 1 if the block is stale or a
                                                  # count is typed outside it

The register is read from --register (a file path or an https URL), else from the
SITE_CLAIMS_REGISTER environment variable, else from REGISTER_URL_DEFAULT.

Exit status: 0 current (or rewritten), 1 stale or a typed count (--check only), 2 the
register or the stat block could not be read. Nothing is written when the exit is 2.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import urllib.request
from pathlib import Path
from urllib.parse import urlsplit

import yaml

ROOT = Path(__file__).resolve().parent.parent
INDEX = ROOT / "index.html"
PAGES = (ROOT / "index.html", ROOT / "docs" / "index.html", ROOT / "README.md")

REGISTER_URL_DEFAULT = "https://raw.githubusercontent.com/bawbel/.github/main/claims/register.yaml"
REGISTER_ENV = "SITE_CLAIMS_REGISTER"
REGISTER_SCHEMA = "bawbel/claims-register/v1"
FETCH_TIMEOUT_SEC = 15
MAX_REGISTER_BYTES = 1024 * 1024

# The stat block in display order: (claim id in the register, label). The register's
# appears_in patterns match these labels, so a label change needs a register change.
STATS = (
    ("C-01", "AVE Records published"),
    ("C-03", "With a detection engine"),
    ("C-06", "Attack Chains"),
    ("C-08", "Detection Engines"),
    ("C-07", "Detection Rules"),
)

START = "<!-- stat:start (generated by scripts/sync_site_numbers.py from the claims register) -->"
END = "<!-- stat:end -->"
BLOCK = re.compile(r"(?P<indent>[ \t]*)<!-- stat:start[^>]*-->\n.*?<!-- stat:end -->", re.S)

# A count typed into prose: "51 AVE records", "121 rules total", "6 Detection Engines".
# One space only: sample output such as "Findings: 2  Chains: 1" uses two.
TYPED_COUNT = re.compile(
    r"(?i)\b\d+ (?:(?:published|built-in|AVE|detection|toxic flow|attack|capability) )*"
    r"(?:records?|rules?|engines?|chains?|endpoints?)\b"
)
# A count in a shields.io badge: "AVE_records-51".
BADGE_COUNT = re.compile(r"(?i)(?<![a-z])(?:records?|rules?|engines?|chains?|endpoints?)-\d+\b")
# Sample terminal output is quoted, not claimed, so <pre> blocks are not checked.
PRE = re.compile(r"<pre\b.*?</pre>", re.S | re.I)


class RegisterError(Exception):
    """The register could not be read, or lacks a value the site needs."""


def read_register(source: str) -> dict:
    """The parsed register from a file path or an https URL."""
    if os.path.isfile(source):
        text = Path(source).read_text(encoding="utf-8")
    else:
        parts = urlsplit(source)
        if parts.scheme != "https" or not parts.netloc:
            raise RegisterError(f"not a file or an https URL: {source}")
        req = urllib.request.Request(source, headers={"User-Agent": "bawbel-site-numbers"})
        try:
            # B310: the scheme is checked above, so only https reaches urlopen.
            with urllib.request.urlopen(req, timeout=FETCH_TIMEOUT_SEC) as resp:  # nosec B310
                body = resp.read(MAX_REGISTER_BYTES + 1)
        except OSError as exc:  # URLError, HTTPError, and timeouts are all OSError
            raise RegisterError(f"{source}: {exc}") from exc
        if len(body) > MAX_REGISTER_BYTES:
            raise RegisterError(f"{source}: larger than {MAX_REGISTER_BYTES} bytes")
        text = body.decode("utf-8", errors="replace")
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise RegisterError(f"{source}: not YAML: {exc}") from exc
    if not isinstance(data, dict) or data.get("schema") != REGISTER_SCHEMA:
        raise RegisterError(f"{source}: not a {REGISTER_SCHEMA} document")
    return data


def stat_values(register: dict) -> dict[str, int]:
    """The expect value of every claim in STATS. Each must be a whole number."""
    claims = {c.get("id"): c for c in register.get("claims") or [] if isinstance(c, dict)}
    values = {}
    for claim_id, _ in STATS:
        expect = (claims.get(claim_id) or {}).get("expect")
        if isinstance(expect, bool) or not isinstance(expect, int) or expect < 0:
            raise RegisterError(f"{claim_id}: expect is not a whole number: {expect!r}")
        values[claim_id] = expect
    return values


def render_block(values: dict[str, int], indent: str) -> str:
    lines = [indent + START]
    for claim_id, label in STATS:
        lines.append(
            f'{indent}<div class="stat"><div class="stat-num">{values[claim_id]}</div>'
            f'<div class="stat-label">{label}</div></div>'
        )
    lines.append(indent + END)
    return "\n".join(lines)


def typed_counts(path: Path) -> list[str]:
    """Counts typed into a page outside the stat block and <pre> samples."""

    def blank(match: re.Match) -> str:
        return "\n" * match.group(0).count("\n")  # keep line numbers

    text = PRE.sub(blank, BLOCK.sub(blank, path.read_text(encoding="utf-8")))
    return [
        f"{path.relative_to(ROOT)}:{lineno}: {match.group(0)!r}"
        for lineno, line in enumerate(text.splitlines(), 1)
        for pattern in (TYPED_COUNT, BADGE_COUNT)
        for match in pattern.finditer(line)
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="change nothing; exit 1 if the block is stale or a count is typed")
    parser.add_argument("--register", default=os.environ.get(REGISTER_ENV) or REGISTER_URL_DEFAULT,
                        help="claims register: a file path or an https URL")
    args = parser.parse_args(argv)

    try:
        values = stat_values(read_register(args.register))
    except RegisterError as exc:
        print(f"sync_site_numbers: {exc}", file=sys.stderr)
        return 2

    html = INDEX.read_text(encoding="utf-8")
    match = BLOCK.search(html)
    if match is None:
        print("sync_site_numbers: index.html has no stat:start/stat:end block", file=sys.stderr)
        return 2
    updated = html[: match.start()] + render_block(values, match.group("indent")) + html[match.end():]
    summary = ", ".join(f"{claim_id} {values[claim_id]}" for claim_id, _ in STATS)

    if args.check:
        problems = []
        if updated != html:
            problems.append("index.html: the stat block is stale; run scripts/sync_site_numbers.py")
        for page in PAGES:
            problems += [f"{hit}: a count typed outside the stat block" for hit in typed_counts(page)]
        for problem in problems:
            print(problem, file=sys.stderr)
        if problems:
            return 1
        print(f"site numbers match the claims register: {summary}")
        return 0

    if updated == html:
        print(f"index.html: stat block already current: {summary}")
    else:
        INDEX.write_text(updated, encoding="utf-8")
        print(f"index.html: stat block updated: {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
